    private void btnHitungActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHitungActionPerformed
if (txtNamaBarang.getText().trim().isEmpty()) {
        tampilkanPeringatan("Nama barang wajib diisi!", txtNamaBarang);
        return;
    }
    if (txtHarga.getText().trim().isEmpty()) {
        tampilkanPeringatan("Harga satuan wajib diisi!", txtHarga);
        return;
    }
    if (txtJumlah.getText().trim().isEmpty()) {
        tampilkanPeringatan("Jumlah pembelian wajib diisi!", txtJumlah);
        return;
    }

    try {
        double harga = parseAngka(txtHarga.getText());
        int jumlah = Integer.parseInt(txtJumlah.getText().trim());

        if (harga < 0) {
            tampilkanPeringatan("Harga tidak boleh negatif!", txtHarga);
            return;
        }
        if (jumlah <= 0) {
            tampilkanPeringatan("Jumlah pembelian harus lebih dari nol!", txtJumlah);
            return;
        }

        totalHarga = harga * jumlah;
        txtTotalHarga.setText(formatRupiah(totalHarga));
    } catch (NumberFormatException e) {
        tampilkanPeringatan("Harga dan jumlah harus berupa angka!", txtHarga);
    }
        // TODO add your handling code here:
    }//GEN-LAST:event_btnHitungActionPerformed

    private void btnBayarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBayarActionPerformed
if (txtTotalHarga.getText().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Klik tombol Hitung terlebih dahulu!", "Peringatan",
                javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }
    if (txtPembayaran.getText().trim().isEmpty()) {
        tampilkanPeringatan("Uang pembayaran wajib diisi!", txtPembayaran);
        return;
    }

    try {
        double bayar = parseAngka(txtPembayaran.getText());

        if (bayar < 0) {
            tampilkanPeringatan("Uang pembayaran tidak boleh negatif!", txtPembayaran);
            return;
        }
        if (bayar < totalHarga) {
            double kurang = totalHarga - bayar;
            tampilkanPeringatan("Pembayaran kurang " + formatRupiah(kurang), txtPembayaran);
            txtKembalian.setText("");
            return;
        }

        double kembalian = bayar - totalHarga;
        txtKembalian.setText(formatRupiah(kembalian));
    } catch (NumberFormatException e) {
        tampilkanPeringatan("Uang pembayaran harus berupa angka!", txtPembayaran);
    }
        // TODO add your handling code here:
    }//GEN-LAST:event_btnBayarActionPerformed

