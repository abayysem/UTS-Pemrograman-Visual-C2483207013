// Mengubah teks menjadi angka, "Rp15.000" atau "15.000" tetap bisa dibaca
private double parseAngka(String teks) {
    String bersih = teks.trim().replace("Rp", "").replace(".", "").replace(" ", "");
    return Double.parseDouble(bersih);
}

private String formatRupiah(double nilai) {
    java.text.DecimalFormat df = new java.text.DecimalFormat("#,###");
    return "Rp" + df.format(nilai).replace(",", ".");
}

